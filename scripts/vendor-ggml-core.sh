#!/bin/bash
#
# scripts/vendor-ggml-core.sh — vendor the CPU-only ggml core that the
# Silero VAD (swift/Sources/silero_vad/upstream-vad/, see
# scripts/vendor-silero-vad.sh) runs on, into
# swift/Sources/silero_vad/upstream/.
#
# Pinned to ggml v0.13.0 (e705c5f), the same commit the tree has carried
# since it came in as parakeet.cpp's submodule; the parakeet.cpp engine and
# ggml's Vulkan backend were dropped on 2026-10-17 when speech recognition
# moved to ONNX on the CPU (docs/specs/cross-platform-onnx-asr-spec.md,
# revision 3). The app process has no GPU code; the GPU belongs to
# SuperDictateLLMHost (scripts/vendor-llama-cpp.sh, its own ggml).
#
# Vendored: the ggml core sources, every public ggml header, the BLAS
# backend (Accelerate) and the CPU backend with its x86 arch code only.
# The tinyBLAS bounds patch below is re-applied on every run.
#
# Usage: scripts/vendor-ggml-core.sh   (needs git and network access)

set -euo pipefail

GGML_COMMIT="e705c5fed490514458bdd2eaddc43bd098fcce9b"
GGML_TAG="v0.13.0"
GGML_REMOTE="https://github.com/ggml-org/ggml.git"

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
UPSTREAM_DEST="$ROOT_DIR/swift/Sources/silero_vad/upstream"

WORK_DIR="$(mktemp -d)"
trap 'rm -rf "$WORK_DIR"' EXIT

echo "vendor-ggml-core.sh: cloning ggml @ $GGML_COMMIT ($GGML_TAG) ..."
git clone --quiet "$GGML_REMOTE" "$WORK_DIR/ggml"
git -C "$WORK_DIR/ggml" checkout --quiet "$GGML_COMMIT"
ACTUAL_COMMIT="$(git -C "$WORK_DIR/ggml" rev-parse HEAD)"
if [[ "$ACTUAL_COMMIT" != "$GGML_COMMIT" ]]; then
    echo "vendor-ggml-core.sh: FATAL: checked out $ACTUAL_COMMIT, expected $GGML_COMMIT" >&2
    exit 1
fi
GGML_SRC="$WORK_DIR/ggml"

rm -rf "$UPSTREAM_DEST"
mkdir -p "$UPSTREAM_DEST/include" "$UPSTREAM_DEST/ggml-cpu"

for f in ggml.c ggml.cpp ggml-alloc.c ggml-backend.cpp ggml-backend-reg.cpp \
         ggml-backend-impl.h ggml-backend-dl.h ggml-backend-dl.cpp \
         ggml-backend-meta.cpp ggml-common.h ggml-impl.h ggml-opt.cpp \
         ggml-quants.c ggml-quants.h ggml-threading.cpp ggml-threading.h \
         gguf.cpp; do
    cp "$GGML_SRC/src/$f" "$UPSTREAM_DEST/$f"
done
cp "$GGML_SRC/include/"*.h "$UPSTREAM_DEST/include/"
cp "$GGML_SRC/src/ggml-blas/ggml-blas.cpp" "$UPSTREAM_DEST/ggml-blas.cpp"
cp -R "$GGML_SRC/src/ggml-cpu/." "$UPSTREAM_DEST/ggml-cpu/"
# x86 only: drop every other architecture and the CMake build glue.
rm -rf \
    "$UPSTREAM_DEST/ggml-cpu/arch/arm" \
    "$UPSTREAM_DEST/ggml-cpu/arch/riscv" \
    "$UPSTREAM_DEST/ggml-cpu/arch/powerpc" \
    "$UPSTREAM_DEST/ggml-cpu/arch/s390" \
    "$UPSTREAM_DEST/ggml-cpu/arch/wasm" \
    "$UPSTREAM_DEST/ggml-cpu/arch/loongarch" \
    "$UPSTREAM_DEST/ggml-cpu/spacemit" \
    "$UPSTREAM_DEST/ggml-cpu/kleidiai" \
    "$UPSTREAM_DEST/ggml-cpu/cmake" \
    "$UPSTREAM_DEST/ggml-cpu/CMakeLists.txt"
cp "$GGML_SRC/LICENSE" "$UPSTREAM_DEST/LICENSE-ggml.txt"

# tinyBLAS (llamafile sgemm) asserts on malformed GEMM shapes; in a release
# build the assert is gone and a bad shape reads out of bounds. Return
# false instead, so ggml falls back to its generic path.
python3 - "$UPSTREAM_DEST/ggml-cpu/llamafile/sgemm.cpp" <<'PY'
from pathlib import Path
import sys

path = Path(sys.argv[1])
text = path.read_text()
needle = "    assert(m >= 0);\n"
replacement = ("    if (m < 0 || n < 0 || k < 0 || lda < k || ldb < k || ldc < m) {\n"
               "        return false;\n"
               "    }\n\n"
               "    assert(m >= 0);\n")
if needle not in text:
    raise SystemExit("vendor-ggml-core.sh: tinyBLAS assert location not found")
path.write_text(text.replace(needle, replacement, 1))
PY

cat > "$UPSTREAM_DEST/PROVENANCE.md" <<PROV
# Vendored upstream provenance (generated by scripts/vendor-ggml-core.sh)

Do not hand-edit anything under this directory — re-run the vendor script.

- ggml: $GGML_REMOTE
  commit: $ACTUAL_COMMIT ($GGML_TAG)
- Vendored: core sources, public headers, the BLAS backend (Accelerate)
  and the CPU backend (x86 arch code only). No GPU backend: the Silero VAD
  that runs on this tree is CPU only.
- Local patch: tinyBLAS bounds check in ggml-cpu/llamafile/sgemm.cpp (see
  the vendor script).
- License: MIT. See LICENSE-ggml.txt.
PROV

file_count=$(find "$UPSTREAM_DEST" -type f | wc -l | tr -d ' ')
echo "vendor-ggml-core.sh: vendored $file_count files ($(du -sh "$UPSTREAM_DEST" | cut -f1)) into $UPSTREAM_DEST"
